import "server-only";

import { cache } from "react";

import { getWizardDocument } from "@/features/ifu-wizard/queries";
import { getApplicableSections } from "@/features/ifu-wizard/rules/applicability";
import type { DeviceProfile, DocumentStatus, SectionKey } from "@/features/ifu-wizard/types";
import { prisma } from "@/lib/prisma";

import { SECTION_CATALOGUE } from "./catalogue";
import type { StructuredValues } from "./schema";
import { readSections, type SectionContentMap } from "./stored";
import type { LicencePreviewInfo } from "./types";

export interface SectionsWorkspaceData {
  documentId: string;
  deviceName: string;
  status: DocumentStatus;
  basicInfoValid: boolean;
  categoryRiskValid: boolean;
  profile: DeviceProfile;
  applicable: SectionKey[];
  content: SectionContentMap;
  /** Applicable sections that count as complete; auto-generated ones follow Step 1 validity. */
  completeKeys: SectionKey[];
  structured: StructuredValues;
  licence: LicencePreviewInfo;
}

/** Cached per request so the sections layout and the section page share one query. */
export const getSectionsWorkspace = cache(async (documentId: string, userId: string): Promise<SectionsWorkspaceData> => {
  const doc = await getWizardDocument(documentId, userId);
  const rows = await prisma.ifuSection.findMany({ where: { documentId }, select: { key: true, fields: true, isComplete: true } });

  const { content, structured } = readSections(rows, doc.basicInfo.description);
  const applicable = getApplicableSections(doc.profile);
  const completeKeys = applicable.filter((key) =>
    SECTION_CATALOGUE[key].autoGenerated ? doc.basicInfoValid : content[key]?.isComplete === true,
  );
  const { basicInfo } = doc;

  return {
    documentId: doc.id,
    deviceName: doc.deviceName,
    status: doc.status,
    basicInfoValid: doc.basicInfoValid,
    categoryRiskValid: doc.categoryRiskValid,
    profile: doc.profile,
    applicable,
    content,
    completeKeys,
    structured,
    licence: {
      manufacturerType: basicInfo.manufacturerType,
      manufacturerName: basicInfo.manufacturerName,
      manufacturerAddress: basicInfo.manufacturerAddress,
      manufacturerState: basicInfo.manufacturerState,
      manufacturerPin: basicInfo.manufacturerPin,
      manufacturerCountry: basicInfo.manufacturerCountry || "India",
      licenceType: basicInfo.licenceType,
      licenceNumber: basicInfo.licenceNumber,
      importerName: basicInfo.importerName,
      importerAddress: basicInfo.importerAddress,
      customerCarePhone: basicInfo.customerCarePhone,
      customerCareEmail: basicInfo.customerCareEmail,
    },
  };
});
