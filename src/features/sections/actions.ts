"use server";

import { revalidatePath } from "next/cache";

import { getStepIndex } from "@/features/ifu-wizard/navigation";
import { getApplicableSections } from "@/features/ifu-wizard/rules/applicability";
import type { DeviceProfile } from "@/features/ifu-wizard/types";
import { type ActionResult, fail, fromZodError, ok } from "@/lib/action-result";
import type { Prisma } from "@/generated/prisma/client";
import { prisma } from "@/lib/prisma";
import { recordAuditEvent } from "@/server/services/audit";
import { DocumentNotFoundError, getOwnedDocumentOrThrow } from "@/server/services/documents/get-owned-document";
import { markComplianceStale } from "@/server/services/documents/mark-compliance-stale";
import { getSession } from "@/server/services/session";

import { SECTION_CATALOGUE } from "./catalogue";
import { sanitiseRichText } from "./sanitise";
import { buildSectionContentSchema, buildSectionDraftSchema, sectionPayloadSchema } from "./schema";
import { pickStructured, validateStructured } from "./structured";
import { STRUCTURED_FIELD_KEY } from "./stored";
import { isHtmlEmpty } from "./text";

export interface SaveSectionData {
  savedAt: string;
  isComplete: boolean;
}

type Mode = "save" | "complete";

/** Shared by `saveSection` and `markSectionComplete`: validate, sanitise, store, stale the compliance run, audit. */
const persistSection = async (input: unknown, mode: Mode): Promise<ActionResult<SaveSectionData>> => {
  const session = await getSession();
  if (!session) return fail("UNAUTHENTICATED", "Please sign in again.");

  const envelope = sectionPayloadSchema.safeParse(input);
  if (!envelope.success) return fromZodError(envelope.error);
  const { documentId, sectionKey, structured, autosave } = envelope.data;

  const definition = SECTION_CATALOGUE[sectionKey];
  if (definition.autoGenerated) return fail("VALIDATION", "This section is generated from Step 1 and can't be edited.");

  // Only catalogue fields are accepted; anything else in the payload is dropped.
  const rawFields = Object.fromEntries(definition.fields.map((field) => [field.key, envelope.data.fields[field.key] ?? ""]));
  const parsed = (mode === "complete" ? buildSectionContentSchema : buildSectionDraftSchema)(definition.fields).safeParse(rawFields);
  if (!parsed.success) return fromZodError(parsed.error, "A few fields need more detail before this section is complete.");

  if (mode === "complete") {
    const structuredErrors = validateStructured(definition.structured, structured);
    if (Object.keys(structuredErrors).length > 0) {
      return fail(
        "VALIDATION",
        "A few fields need more detail before this section is complete.",
        Object.fromEntries(Object.entries(structuredErrors).map(([key, message]) => [key, [message]])),
      );
    }
  }

  // Sanitise after validating visible length, then store only the markup the editor can produce (NFR-SEC-02).
  const fields: Record<string, string> = {};
  for (const field of definition.fields) fields[field.key] = sanitiseRichText(parsed.data[field.key] ?? "");
  const stored: Prisma.InputJsonObject = {
    ...fields,
    ...(definition.structured ? { [STRUCTURED_FIELD_KEY]: pickStructured(structured, definition.structured) } : {}),
  };
  const hasEmptyField = Object.values(fields).some(isHtmlEmpty);

  try {
    const doc = await getOwnedDocumentOrThrow(documentId, session.user.id, {
      id: true,
      lastStep: true,
      category: true,
      isSterile: true,
      isReusable: true,
      isActive: true,
      hasMeasuringFn: true,
      isLayUser: true,
      riskClass: true,
    });
    const profile: DeviceProfile = { ...doc };
    if (!getApplicableSections(profile).includes(sectionKey)) return fail("VALIDATION", "This section doesn't apply to your device.");

    const isComplete = await prisma.$transaction(async (tx) => {
      const advance = getStepIndex(doc.lastStep) < getStepIndex("SECTIONS");
      // Ownership and soft-delete are re-checked in the write itself, closing the check-then-write race.
      const { count } = await tx.ifuDocument.updateMany({
        where: { id: doc.id, ownerId: session.user.id, deletedAt: null },
        data: { updatedAt: new Date(), ...(advance ? { lastStep: "SECTIONS" as const } : {}) },
      });
      if (count === 0) throw new DocumentNotFoundError();

      const existing = await tx.ifuSection.findUnique({
        where: { documentId_key: { documentId: doc.id, key: sectionKey } },
        select: { isComplete: true },
      });
      // FR-S3-09: a completed section stays complete unless one of its fields is emptied.
      const complete = mode === "complete" || (existing?.isComplete === true && !hasEmptyField);

      await tx.ifuSection.upsert({
        where: { documentId_key: { documentId: doc.id, key: sectionKey } },
        create: { documentId: doc.id, key: sectionKey, fields: stored, isComplete: complete },
        update: { fields: stored, isComplete: complete },
      });
      await markComplianceStale(doc.id, tx);
      if (!autosave) {
        await recordAuditEvent(
          {
            userId: session.user.id,
            action: "UPDATED",
            documentId: doc.id,
            meta: { step: "SECTIONS", section: sectionKey, event: mode === "complete" ? "SECTION_COMPLETED" : "SECTION_SAVED" },
          },
          tx,
        );
      }
      return complete;
    });

    if (!autosave) revalidatePath("/dashboard");
    return ok({ savedAt: new Date().toISOString(), isComplete });
  } catch (error) {
    if (error instanceof DocumentNotFoundError) return fail("NOT_FOUND", "Document not found.");
    console.error("persistSection failed", { userId: session.user.id, documentId, sectionKey, error });
    return fail("INTERNAL", "Couldn't save your changes. Please try again.");
  }
};

/** FR-S3-07/08: autosave (2 s and on blur) and save-on-navigate. Never marks a section complete. */
export const saveSectionAction = async (input: unknown): Promise<ActionResult<SaveSectionData>> => persistSection(input, "save");

/** FR-S3-06: validates minimum content per field, stores it and marks the section complete. */
export const markSectionCompleteAction = async (input: unknown): Promise<ActionResult<SaveSectionData>> =>
  persistSection(input, "complete");
