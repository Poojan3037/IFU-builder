import { SECTION_CATALOGUE, SECTION_ORDER } from "@/features/sections/catalogue";

import { containsAny, PHRASES } from "../phrases";
import type { ComplianceRule } from "../types";
import { fieldText, isApplicable, sectionText } from "./helpers";

/** Average words per sentence at or above this fails the lay-user readability heuristic. */
const MAX_AVERAGE_SENTENCE_WORDS = 25;

export const getAverageSentenceLength = (text: string): number => {
  const sentences = text.split(/[.!?\n]+/).filter((sentence) => sentence.trim() !== "");
  if (sentences.length === 0) return 0;
  const words = sentences.reduce((total, sentence) => total + sentence.trim().split(/\s+/).length, 0);
  return words / sentences.length;
};

/** IN-VIG (adverse events), IN-DSP (disposal) and IN-LAY (lay-user readability) rules. */
export const postMarketRules: ComplianceRule[] = [
  {
    id: "IN-VIG-001",
    severity: "ADVISORY",
    appliesWhen: () => true,
    check: (doc) => {
      const text = fieldText(doc, "vigilance", "reporting");
      const hasCompanyRoute =
        containsAny(text, PHRASES.companyContact) ||
        /\d{6,}/.test(text.replace(/[\s-]/g, "")) ||
        (doc.info.manufacturerName !== "" && text.toLowerCase().includes(doc.info.manufacturerName.toLowerCase()));
      return containsAny(text, PHRASES.mvpi) && hasCompanyRoute;
    },
    title: "No adverse-event reporting route",
    message: "Tell users how to report incidents to your company and to the Materiovigilance Programme of India (MvPI).",
    sectionKey: "vigilance",
    fieldKey: "reporting",
    reference: "Materiovigilance Programme of India [verify]",
    passNote: "company and MvPI routes given",
  },
  {
    id: "IN-DSP-001",
    severity: "ADVISORY",
    appliesWhen: ({ profile }) => profile.category === "IMPLANT" || profile.isActive === true,
    check: (doc) => containsAny(fieldText(doc, "disposal", "disposal"), PHRASES.wasteRules),
    title: "Disposal doesn't reference the waste rules",
    message: "Refer to the Bio-Medical Waste Management Rules, 2016 (and the E-Waste Rules for powered devices) in Disposal Instructions.",
    sectionKey: "disposal",
    fieldKey: "disposal",
    reference: "Bio-Medical Waste Management Rules, 2016 [verify]",
    passNote: "waste rules referenced",
  },
  ...SECTION_ORDER.flatMap<ComplianceRule>((sectionKey) => {
    const definition = SECTION_CATALOGUE[sectionKey];
    if (definition.autoGenerated) return [];
    return [
      {
        id: "IN-LAY-001",
        severity: "ADVISORY",
        appliesWhen: (doc) => doc.profile.isLayUser === true && isApplicable(doc, sectionKey) && sectionText(doc, sectionKey) !== "",
        check: (doc) => getAverageSentenceLength(sectionText(doc, sectionKey)) < MAX_AVERAGE_SENTENCE_WORDS,
        title: `${definition.title} may be hard for lay users to read`,
        message: `Sentences here average ${MAX_AVERAGE_SENTENCE_WORDS}+ words. For home users, use short sentences and plain words.`,
        sectionKey,
        reference: "Readability heuristic",
      },
    ];
  }),
];
