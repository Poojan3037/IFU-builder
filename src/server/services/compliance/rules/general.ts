import { SECTION_CATALOGUE, SECTION_ORDER } from "@/features/sections/catalogue";
import { isHtmlEmpty } from "@/features/sections/text";

import type { ComplianceRule } from "../types";
import { fieldText, isApplicable } from "./helpers";

/** Narrative fields only: short-by-design fields (e.g. "Materials", "None known") would just add noise. */
const NARRATIVE_MIN_CATALOGUE_LENGTH = 30;
const MEANINGFUL_LENGTH = 40;

/** IN-GEN-001 / IN-GEN-002 fan out per section and per field from the catalogue. */
export const generalRules: ComplianceRule[] = SECTION_ORDER.flatMap((sectionKey) => {
  const definition = SECTION_CATALOGUE[sectionKey];
  // The licence section is generated from Step 1; the IN-LBL rules cover it.
  if (definition.autoGenerated) return [];

  const complete: ComplianceRule = {
    id: "IN-GEN-001",
    severity: "BLOCKING",
    appliesWhen: (doc) => isApplicable(doc, sectionKey),
    check: (doc) =>
      doc.sections[sectionKey]?.isComplete === true && definition.fields.every((field) => fieldText(doc, sectionKey, field.key) !== ""),
    title: `${definition.title} isn't complete`,
    message: `Fill in every field of “${definition.title}” and mark the section complete. Required sections can't be skipped.`,
    sectionKey,
    fieldKey: definition.fields[0]?.key,
    reference: "MDR 2017, Rule 44 [verify]",
  };

  const meaningful = definition.fields
    .filter((field) => field.minLength >= NARRATIVE_MIN_CATALOGUE_LENGTH)
    .map<ComplianceRule>((field) => ({
      id: "IN-GEN-002",
      severity: "ADVISORY",
      appliesWhen: (doc) => isApplicable(doc, sectionKey) && !isHtmlEmpty(fieldText(doc, sectionKey, field.key)),
      check: (doc) => fieldText(doc, sectionKey, field.key).length >= MEANINGFUL_LENGTH,
      title: `${field.label} looks very short`,
      message: `“${field.label}” has fewer than ${MEANINGFUL_LENGTH} characters. Add enough detail for a user to act on it.`,
      sectionKey,
      fieldKey: field.key,
    }));

  return [complete, ...meaningful];
});
